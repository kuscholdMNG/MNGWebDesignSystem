def sort_sizes(d):
    keys = [k for k in d if not k.startswith('$')]
    keys.sort(key=lambda k: float(k.replace('-', '.')))
    return {**{k: d[k] for k in d if k.startswith('$')}, **{k: d[k] for k in keys}}
core_type['font']['size'] = sort_sizes(core_type['font']['size'])

weight_ref = {400: '{font.weight.regular}', 500: '{font.weight.medium}', 600: '{font.weight.semibold}', 700: '{font.weight.bold}'}

def ref(figval, kind):
    """Figma alias or literal -> DTCG reference (preferring an existing primitive) or literal."""
    if isinstance(figval, str) and figval.startswith('{'):
        return '{' + figval[1:-1].replace('/', '.') + '}'
    if kind == 'size':
        px = num(figval, 3)
        return size_by_px.get(px, {'value': px, 'unit': 'px'})
    if kind == 'weight':
        return weight_ref.get(int(figval), int(figval))
    if kind == 'family':
        return fam_map.get(figval, [figval])
    return figval

