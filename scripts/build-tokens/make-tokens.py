HERE = os.path.dirname(os.path.abspath(__file__))
FIGMA_FILE = 'MNG Web Design System'
DIFF_ENTRY_COLORS = 21

def load(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return json.load(f)

def write(p, data):
    p = os.path.join(ROOT, p)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, 'w', encoding='utf-8') as f:
        json.dump(data, f, indent=2, ensure_ascii=False)
        f.write('\n')

def num(x, nd=4):
    """Round Figma float noise (15.199999809 -> 15.2) and drop .0."""
    x = round(float(x), nd)
    return int(x) if x == int(x) else x

def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

# ---------- colors ----------
def color_value(hexstr, alpha=1):
    h = hexstr.lower()
    if not re.fullmatch(r'#[0-9a-f]{6}', h):
        raise ValueError('bad hex ' + hexstr)
    rgb = [int(h[i:i + 2], 16) for i in (1, 3, 5)]
    val = {'colorSpace': 'srgb', 'components': [num(c / 255) for c in rgb], 'alpha': num(alpha), 'hex': h}
    ext = {'rgba': 'rgba(%d, %d, %d, %s)' % (rgb[0], rgb[1], rgb[2], num(alpha))}
    if alpha < 1:
        ext['hex8'] = h + '%02x' % round(alpha * 255)
    return val, ext

def color_token(hexstr, description=None, figma=None, production=None, alpha=1, extra=None):
    val, ext = color_value(hexstr, alpha)
    t = {'$value': val}
    if description:
        t['$description'] = description
    mng = dict(ext)
    mng['figma'] = figma
    if production:
        mng['production'] = production
    if extra:
        mng.update(extra)
    t['$extensions'] = {'com.mng': mng}
    return t

def parse_figma_color(v):
    if '@' in v:
        h, a = v.split('@')
        return h, float(a)
    return v, 1

