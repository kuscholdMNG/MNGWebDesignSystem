def bp_doc(setinfo, path):
    grp = {'$type': 'dimension'}
    for t in setinfo['tokens']:
        tok = {'$value': {'value': t['minWidth'], 'unit': 'px'}, '$description': t['description']}
        mng = {}
        if 'figmaFrameWidth' in t:
            mng['figma'] = {'file': FIGMA_FILE, 'frameWidth': t['figmaFrameWidth']}
        if 'production' in t:
            mng['production'] = t['production']
        if mng:
            tok['$extensions'] = {'com.mng': mng}
        grp[t['name']] = tok
    node = grp
    for p in reversed(path):
        node = {p: node}
    return {'$description': setinfo['description'], **node}
write('tokens/core/breakpoint.tokens.json', bp_doc(bp['device'], ['breakpoint']))
