# ---------- JS / TS ----------
def nested(toks, names):
    root = {}
    for n in names:
        t = toks[n]
        parts = n.split('.')
        node = root
        for p in parts[:-1]:
            node = node.setdefault(p, {})
        if t['type'] == 'typography':
            v = t['value']
            o = {}
            for key, suffix, ptype in TYPO_PARTS:
                x = v[key]
                m = REF.match(x) if isinstance(x, str) else None
                if key == 'fontFamily' and m and m.group(1).startswith('font.theme.'):
                    o[key] = 'var(%s)' % css_name(m.group(1))  # follows the theme at runtime
                elif key == 'fontWeight' or key == 'lineHeight':
                    o[key] = float(resolve(toks, x)) if key == 'lineHeight' else int(resolve(toks, x))
                else:
                    o[key] = resolved_literal(toks, ptype, x)
            if 'lineHeightPx' in t['ext']:
                o['lineHeightPx'] = '%spx' % num(t['ext']['lineHeightPx'])
            o['cssVar'] = css_name(n)
            node[parts[-1]] = o
            continue
        rv = resolve(toks, t['value'])
        if t['type'] == 'fontWeight':
            val = int(rv)
        else:
            val = fmt_literal(t['type'], rv)
        node[parts[-1]] = val
    return root

def js_obj(o):
    return json.dumps(o, indent=2, ensure_ascii=False)

