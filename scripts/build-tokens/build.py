def v3_theme():
    colors, fam, size, weight, spacing, radius, screens = {}, {}, {}, {}, {}, {}, {}
    for n in core_names:
        t = core[n]
        rv = resolve(core, t['value'])
        val = fmt_literal(t['type'], rv)
        p = n.split('.')
        if p[0] == 'color':
            colors.setdefault(p[1], {})[p[2]] = val
        elif p[:2] == ['font', 'family']:
            fam[p[2]] = rv if isinstance(rv, list) else [rv]
        elif p[:2] == ['font', 'size']:
            size[p[2]] = val
        elif p[:2] == ['font', 'weight']:
            weight[p[2]] = val
        elif p[0] == 'spacing':
            spacing['%s-%s' % (PREFIX, p[1])] = val
        elif p[0] == 'radius':
            radius[p[1]] = val
        elif p[0] == 'breakpoint':
            screens[p[1]] = val
    for n in wp_names:
        if n.startswith('breakpoint.wordpress-grid.'):
            screens['wp-' + n.split('.')[-1]] = fmt_dim(wp_only[n]['value'])
    colors['theme'] = {tw_key(n, 'color.theme.'): 'var(%s)' % css_name(n) for n in theme_color_names}
    for n in sorted({n for k in theme_keys for n in theme_own(k) if n.startswith('font.theme.') and n.endswith('family')}):
        fam['theme-' + tw_key(n, 'font.theme.').replace('-family', '')] = ['var(%s)' % css_name(n)]
    return {'theme': {'extend': {'colors': colors, 'fontFamily': fam, 'fontSize': size, 'fontWeight': weight,
                                 'spacing': spacing, 'borderRadius': radius, 'screens': screens}}}
