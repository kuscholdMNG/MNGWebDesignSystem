def theme_json(k):
    toks = brand_sets[k]
    palette = []
    for n in core_names + list(theme_own(k)):
        t = toks[n]
        if t['type'] == 'color':
            s = n.replace('color.', '', 1).replace('.', '-')
            palette.append({'slug': s, 'name': s.replace('-', ' ').title(), 'color': resolved_literal(toks, 'color', t['value'])})
    fams = []
    for n in [x for x in core_names if x.startswith('font.family.')] + \
             [x for x in theme_own(k) if x.startswith('font.theme.') and x.endswith('family')]:
        s = n.split('.')[-1].replace('-family', '')
        fams.append({'slug': s, 'name': s.replace('-', ' ').title(), 'fontFamily': resolved_literal(toks, 'fontFamily', toks[n]['value'])})
    sizes = [{'slug': n.split('.')[-1], 'name': n.split('.')[-1].replace('-', '.') + 'px',
              'size': resolved_literal(toks, 'dimension', toks[n]['value'])} for n in core_names if n.startswith('font.size.')]
    spacing = [{'slug': n.split('.')[-1], 'name': '%s (%s)' % (n.split('.')[-1], resolved_literal(toks, 'dimension', toks[n]['value'])),
                'size': resolved_literal(toks, 'dimension', toks[n]['value'])} for n in core_names if n.startswith('spacing.')]
    custom = {'radius': {}, 'breakpoint': {}, 'font-weight': {}}
    for n in core_names + wp_names:
        p = n.split('.')
        if p[0] == 'radius':
            custom['radius'][p[1]] = resolved_literal(toks, 'dimension', toks[n]['value'])
        elif p[0] == 'breakpoint':
            custom['breakpoint']['-'.join(p[1:])] = resolved_literal(toks, 'dimension', toks[n]['value'])
        elif p[:2] == ['font', 'weight']:
            custom['font-weight'][p[2]] = resolved_literal(toks, 'fontWeight', toks[n]['value'])
    for n in theme_own(k):
        if n.startswith('font.theme.') and not n.endswith('family'):
            custom.setdefault('font-theme', {})[n.split('.')[-1]] = resolved_literal(toks, toks[n]['type'], toks[n]['value'])
    return {'$schema': 'https://schemas.wp.org/trunk/theme.json', 'version': 3,
            'title': 'MNG Web Design System: %s' % THEMES[k]['name'],
            'settings': {'color': {'palette': palette},
                         'typography': {'fontFamilies': fams, 'fontSizes': sizes},
                         'spacing': {'spacingSizes': spacing},
                         'custom': custom}}
for k in theme_keys:
    write('wordpress/%s.theme.json' % k, dump(theme_json(k)))

