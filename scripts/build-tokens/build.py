def ts_type(o, ind='  '):
    if isinstance(o, dict):
        inner = ''.join('%s%s: %s;\n' % (ind, json.dumps(k) if not re.fullmatch(r'[A-Za-z_$][\w$]*', k) else k,
                                          ts_type(v, ind + '  ')) for k, v in o.items())
        return '{\n%s%s}' % (inner, ind[:-2])
    if isinstance(o, bool):
        return 'boolean'
    if isinstance(o, (int, float)):
        return 'number'
    if isinstance(o, list):
        return 'string[]'
    if o is None:
        return 'null'
    return 'string'

